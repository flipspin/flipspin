#!/usr/bin/env python3
"""Embed the canonical art in both standalone shell scripts and the server.

Run after changing deploy/art; --check fails without modifying generated files.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = '# BEGIN GENERATED INSTALLER ENDING'
END = '# END GENERATED INSTALLER ENDING'


def shell_ending():
    body = f'{START}\n# Regenerate with: python3 scripts/generate-installer-ending.py\n'
    body += 'ending_scene() {\n    case "$1" in\n'
    for mode, filename in [('truecolor', 'scene.ansi'), ('256', 'scene-256.ansi'), ('plain', 'scene.txt')]:
        delimiter = f'KROBI_SCENE_{mode.upper()}'
        art = (ROOT / 'deploy/art' / filename).read_text(encoding="utf-8")
        body += f"        {mode}) cat <<'{delimiter}'\n{art}{delimiter}\n            ;;\n"
    body += '''    esac
}
# Arguments: running version, HTTP address, setup link, setup code (empty if claimed).
# stdout decides colour even when stdin is the curl pipe. Never call log() here.
print_ending() {
    ending_bold='' ending_dim='' ending_reset='' ending_art=plain
    if [ -t 1 ] && [ "${NO_COLOR+x}" != x ]; then
        ending_bold=$(printf '\\033[1m')
        ending_dim=$(printf '\\033[2m')
        ending_reset=$(printf '\\033[0m')
        case "${COLORTERM:-}" in truecolor|24bit) ending_art=truecolor ;; *) ending_art=256 ;; esac
    fi
    # POSIX locale precedence: an explicit C locale overrides a UTF-8 LANG.
    case "${LC_ALL:-${LC_CTYPE:-${LANG:-}}}" in
        *[Uu][Tt][Ff]-8*|*[Uu][Tt][Ff]8*) printf '\\n'; ending_scene "$ending_art" ;;
    esac
    printf '\\n%sFlipspin is running%s %s· %s%s\\n\\n' "$ending_bold" "$ending_reset" "$ending_dim" "$1" "$ending_reset"
    if [ -n "$4" ]; then
        printf '%s%s%s\\n' "$ending_bold" "$3" "$ending_reset"
        printf '%sPaste it in Flipspin → Setup link%s\\n' "$ending_dim" "$ending_reset"
        printf '%sNest address: %s\\nSetup code: %s%s\\n' "$ending_dim" "$2" "$4" "$ending_reset"
    else
        printf '%s%s%s\\n' "$ending_bold" "$2" "$ending_reset"
        printf '%sAlready set up%s\\n' "$ending_dim" "$ending_reset"
    fi
}
'''
    return body + END


def generated_files():
    for filename in ['deploy/install.sh', 'deploy/krobi']:
        path = ROOT / filename
        original = path.read_text(encoding="utf-8")
        before, rest = original.split(START, 1)
        _, after = rest.split(END, 1)
        yield path, before + shell_ending() + after
    art = (ROOT / 'deploy/art/scene.txt').read_text(encoding="utf-8")
    yield ROOT / 'backend/app/infra/setup_scene.py', (
        '"""Generated by scripts/generate-installer-ending.py; edit deploy/art/scene.txt."""\n\n'
        f'SETUP_SCENE = """{art}"""\n'
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, content in generated_files():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            if args.check:
                drift.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(content, encoding="utf-8")
    if drift:
        parser.exit(1, 'Generated ending drift: ' + ', '.join(drift) + '\nRun python3 scripts/generate-installer-ending.py\n')


if __name__ == '__main__':
    main()
